/**
 * One-time step: self-host Satoshi (Fontshare) and IBM Plex Mono (Google Fonts).
 *
 *   npm run fonts      (needs internet, run once, then commit the result)
 *
 * It downloads the woff2 files into public/fonts/, writes the @font-face rules to src/fonts.css,
 * and replaces the third-party font <link> tags in index.html (between the `fonts:start` / `fonts:end`
 * comments) with preloads for the two weights used above the fold.
 *
 * Until it has been run, the site keeps loading fonts from the two CDNs (index.html), so nothing
 * breaks. Safe to re-run. Check the Fontshare licence for your use before shipping the files.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const FONT_DIR = path.join(ROOT, "public", "fonts");
const CSS_OUT = path.join(ROOT, "src", "fonts.css");
const HTML = path.join(ROOT, "index.html");
// A current Chrome UA, so the providers answer with woff2 files
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

export const SOURCES = [
  {
    family: "Satoshi",
    slug: "satoshi",
    css: "https://api.fontshare.com/v2/css?f[]=satoshi@400,500,700,900&display=swap",
    subsets: null, // keep everything the provider sends
  },
  {
    family: "IBM Plex Mono",
    slug: "ibm-plex-mono",
    css: "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&display=swap",
    subsets: ["latin", "latin-ext"], // Google splits by script; the site only needs these
  },
];
/** Preloaded in index.html: the body weight and the display weight. */
export const PRELOAD = ["satoshi-400", "satoshi-700"];

/** Pulls { subset, weight, style, unicodeRange, url } out of a provider's @font-face CSS. */
export function parseFontFaces(css) {
  const out = [];
  const re = /(?:\/\*\s*([\w-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const [, subset = null, body] = m;
    const prop = (name) => body.match(new RegExp(`${name}\\s*:\\s*([^;]+);`, "i"))?.[1].trim();
    const src = body.match(/url\(\s*['"]?([^'")]+)['"]?\s*\)\s*format\(\s*['"]woff2['"]\s*\)/i)?.[1];
    if (!src) continue;
    out.push({
      subset,
      weight: prop("font-weight") ?? "400",
      style: prop("font-style") ?? "normal",
      unicodeRange: prop("unicode-range") ?? null,
      url: src.startsWith("//") ? `https:${src}` : src,
    });
  }
  return out;
}

export function fileName(source, face) {
  const sub = face.subset && source.subsets ? `-${face.subset}` : "";
  return `${source.slug}-${face.weight.replace(/\s+/g, "-")}${sub}.woff2`;
}

export function fontFaceCss(source, face) {
  const lines = [
    `  font-family: "${source.family}";`,
    `  font-style: ${face.style};`,
    `  font-weight: ${face.weight};`,
    `  font-display: swap;`,
    `  src: url("/fonts/${fileName(source, face)}") format("woff2");`,
  ];
  if (face.unicodeRange) lines.push(`  unicode-range: ${face.unicodeRange};`);
  return `@font-face {\n${lines.join("\n")}\n}\n`;
}

export function fontLinksHtml(files) {
  return PRELOAD.filter((n) => files.includes(`${n}.woff2`))
    .map((n) => `    <link rel="preload" href="/fonts/${n}.woff2" as="font" type="font/woff2" crossorigin />`)
    .join("\n");
}

async function get(url, asBuffer = false) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return asBuffer ? Buffer.from(await res.arrayBuffer()) : res.text();
}

async function main() {
  await fs.mkdir(FONT_DIR, { recursive: true });
  const files = [];
  let css = "/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n";

  for (const source of SOURCES) {
    const faces = parseFontFaces(await get(source.css)).filter(
      (f) => f.style === "normal" && (!source.subsets || source.subsets.includes(f.subset)),
    );
    if (!faces.length) throw new Error(`No usable @font-face rules found for ${source.family}`);
    for (const face of faces) {
      const name = fileName(source, face);
      if (files.includes(name)) continue; // same weight+subset twice: keep the first
      await fs.writeFile(path.join(FONT_DIR, name), await get(face.url, true));
      files.push(name);
      css += fontFaceCss(source, face) + "\n";
      console.log(`  ${name}`);
    }
  }

  await fs.writeFile(CSS_OUT, css);

  let html = await fs.readFile(HTML, "utf8");
  const block = /<!-- fonts:start -->[\s\S]*?<!-- fonts:end -->/;
  if (!block.test(html)) throw new Error("index.html is missing the fonts:start / fonts:end markers");
  html = html.replace(block, `<!-- fonts:start -->\n${fontLinksHtml(files)}\n    <!-- fonts:end -->`);
  await fs.writeFile(HTML, html);

  console.log(`\nDone: ${files.length} font files in public/fonts/, rules in src/fonts.css, index.html updated.`);
  console.log("Run `npm run build` and check the site, then commit public/fonts, src/fonts.css and index.html.");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
